// เทียบ "รหัสที่มีอยู่ในข้อมูล" กับ "รหัสที่ผู้ตรวจสอบให้เอง" แล้วเสนอสัญลักษณ์ผลการตรวจ
//
// ⚠️ นี่คือ "ข้อเสนอ" ไม่ใช่ "คำตัดสิน"
//    ผู้ตรวจสอบต้องเป็นคนเลือกช่องผลการตรวจเองเสมอ ระบบแค่เติมให้ล่วงหน้า
//    เพราะสัญลักษณ์บางตัวตัดสินจากตัวรหัสอย่างเดียวไม่ได้ ต้องเปิดเวชระเบียนดู
//      B = มีรหัสทั้งที่ "ไม่มีคำวินิจฉัยในบันทึก"  → ต้องดูบันทึก
//      C = รหัสด้อยคุณภาพเพราะ "คำวินิจฉัยด้อยคุณภาพ" → ต้องดูคำวินิจฉัย
//    สองตัวนี้ระบบจะไม่เสนอเด็ดขาด ปล่อยให้คนเลือก
//
// ที่เสนอได้เพราะตัดสินจากตัวรหัสล้วนๆ (คู่มือหน้า 15-16 / 25-26)
//   Y = ตรงกัน
//   D = รหัสในข้อมูลสั้นกว่า เป็นต้นทางของรหัสที่ผู้ตรวจให้ → "มีตัวเลขไม่ครบทุกตำแหน่ง"
//   F = รหัสในข้อมูลยาวกว่า → "มีตัวเลขมากเกินไป"
//   E = ใช้สาเหตุภายนอก (V,W,X,Y) เป็นรหัสโรคหลัก
//   G = ผู้ตรวจให้รหัสนี้ แต่ไม่มีในข้อมูล
//   H = มีรหัสในข้อมูล แต่ผู้ตรวจไม่ให้
//   A = ต่างกันโดยสิ้นเชิง → ให้รหัสผิดพลาด

/**
 * ทำให้รหัสเทียบกันได้
 * HOSxP เก็บ ICD-10 แบบไม่มีจุด (J029) แต่คนพิมพ์มักใส่จุด (J02.9)
 * ถ้าไม่ตัดจุดทิ้งก่อน รหัสเดียวกันจะถูกตัดสินว่า "ผิด"
 */
export function normalizeIcd(value: string | null | undefined): string {
  return String(value ?? "")
    .toUpperCase()
    .replace(/[^A-Z0-9]/g, "");
}

/** รหัสสาเหตุภายนอก — ขึ้นต้นด้วย V, W, X หรือ Y */
export function isExternalCause(code: string): boolean {
  return /^[VWXY]/.test(normalizeIcd(code));
}

export type IcdSuggestion = {
  /** สัญลักษณ์ที่เสนอ — null = ตัดสินจากตัวรหัสอย่างเดียวไม่ได้ ต้องให้คนดู */
  code: string | null;
  /** เหตุผลสั้นๆ ไว้แสดงข้างช่อง ให้คนตัดสินใจได้เร็วขึ้น */
  reason: string;
};

/**
 * เสนอสัญลักษณ์ผลการตรวจจากคู่รหัส
 *
 * @param icd       รหัสที่มีอยู่ในข้อมูลเดิม (ดึงมาจาก HOSxP)
 * @param auditIcd  รหัสที่ผู้ตรวจสอบให้เอง
 * @param icdType   ประเภทรหัส — ใช้ตรวจกรณี E ที่นับเฉพาะโรคหลัก (type = 1)
 */
export function suggestIcdResult(
  icd: string | null | undefined,
  auditIcd: string | null | undefined,
  icdType?: string | null,
): IcdSuggestion {
  const a = normalizeIcd(icd);
  const b = normalizeIcd(auditIcd);

  if (a === "" && b === "") {
    return { code: null, reason: "ยังไม่มีรหัสให้เทียบ" };
  }

  if (a === "" && b !== "") {
    return { code: "G", reason: "ผู้ตรวจสอบให้รหัสนี้ แต่ไม่มีในข้อมูลเดิม" };
  }

  if (a !== "" && b === "") {
    return { code: "H", reason: "มีรหัสในข้อมูลเดิม แต่ผู้ตรวจสอบไม่ให้รหัสนี้" };
  }

  // ใช้สาเหตุภายนอกเป็นโรคหลัก — ผิดตั้งแต่ต้น ไม่ต้องดูว่าตรงกับผู้ตรวจไหม
  if (String(icdType ?? "").trim() === "1" && isExternalCause(a)) {
    return { code: "E", reason: "ใช้สาเหตุภายนอก (V,W,X,Y) เป็นรหัสโรคหลัก" };
  }

  if (a === b) {
    return { code: "Y", reason: "ตรงกับรหัสที่ผู้ตรวจสอบให้" };
  }

  // รหัสในข้อมูลสั้นกว่าและเป็นต้นทางของรหัสที่ถูกต้อง → ยังใส่ไม่ครบหลัก
  if (b.startsWith(a)) {
    return {
      code: "D",
      reason: `ควรเป็น ${b} — รหัสในข้อมูลมีตัวเลขไม่ครบทุกตำแหน่ง`,
    };
  }

  // รหัสในข้อมูลยาวเกินกว่าที่ควรเป็น
  if (a.startsWith(b)) {
    return {
      code: "F",
      reason: `ควรเป็น ${b} — รหัสในข้อมูลมีตัวเลขมากเกินไป`,
    };
  }

  return { code: "A", reason: `ควรเป็น ${b} — คนละรหัสกัน` };
}
